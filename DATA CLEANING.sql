-- data cleaning of patient table

-- remove patient rows where first name is missing
-- standardize firstname and lastname to proper case and create a new full name column
-- gender values should be either male or female
-- split citystatecountry into city, state and country columns separately

CREATE TABLE PATIENT_CLEAN(
	PATIENTID VARCHAR(20) PRIMARY KEY,
    FULLNAME VARCHAR(120),
    GENDER VARCHAR(10),
    DOB DATE,
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    COUNTRY VARCHAR(50)
);

INSERT INTO PATIENT_CLEAN(PATIENTID, FULLNAME, GENDER, DOB, CITY, STATE, COUNTRY) 
SELECT 
P.PATIENTID, 

CONCAT(UPPER(LEFT(LTRIM(RTRIM(P.FIRSTNAME)), 1)) , LOWER(SUBSTRING(LTRIM(RTRIM(P.FIRSTNAME)) , 2 , LENGTH(LTRIM(RTRIM(P.FIRSTNAME))))) , ' ',

UPPER(LEFT(LTRIM(RTRIM(P.LASTNAME)), 1)) , LOWER(SUBSTRING(LTRIM(RTRIM(P.LASTNAME)) , 2 , LENGTH(LTRIM(RTRIM(P.LASTNAME))))) )
AS FULLNAME,

CASE 
WHEN P.GENDER = 'M' THEN 'MALE'
WHEN P.GENDER = 'F' THEN 'FEMALE'
ELSE P.GENDER
END AS GENDER,

P.DOB, 

SUBSTRING_INDEX(
	REPLACE(P.CITYSTATECOUNTRY , ',' , '.'),
    '.',
    1)
AS CITY,

SUBSTRING_INDEX(
SUBSTRING_INDEX(
	REPLACE(P.CITYSTATECOUNTRY, ',','.'),
    '.',
    2),
    '.',
    -1)
AS STATE,

SUBSTRING_INDEX(
	REPLACE(P.CITYSTATECOUNTRY,',','.'),
    '.',
    -1)
AS COUNTRY 

FROM PATIENT P 
WHERE P.FIRSTNAME IS NOT NULL;

SELECT * FROM PATIENT_CLEAN;

