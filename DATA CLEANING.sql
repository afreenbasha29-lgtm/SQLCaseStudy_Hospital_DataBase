CREATE TABLE PATIENT_VISITS(
VISIT_ID VARCHAR(10) PRIMARY KEY,
PATIENT_ID VARCHAR(10),
DOCTOR_ID VARCHAR(20),
DEPARTMENT_ID VARCHAR(20),
DIAGNOSIS_ID VARCHAR(20),
TREATMENT_ID VARCHAR(20),
PAYMENT_METHOD_ID VARCHAR(20),
VISIT_DATE DATE,
VISIT_TIME TIME,
DISCHARGE_DATE DATE,
BILL_AMOUNT DECIMAL(18,2),
INSURANCE_AMOUNT DECIMAL(18,2),
SATISFACTION_SCORE INT,
WAIT_TIME_MINUTES INT ,

FOREIGN KEY (PATIENT_ID) REFERENCES PATIENT_CLEAN(PATIENTID),
FOREIGN KEY (DOCTOR_ID) REFERENCES DOCTOR(DOCTORID),
FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENT_CLEAN(DEPARTMENTID),
FOREIGN KEY (DIAGNOSIS_ID) REFERENCES DIAGNOSIS(DIAGNOSISID),
FOREIGN KEY (TREATMENT_ID) REFERENCES TREATMENT(TREATMENTID),
FOREIGN KEY (PAYMENT_METHOD_ID) REFERENCES PAYMENTMETHOD(PAYMENTMETHODID)
);

