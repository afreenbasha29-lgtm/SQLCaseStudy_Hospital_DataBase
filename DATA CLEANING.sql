    DEPARTMENTNAME VARCHAR(50),
    DEPARTMENT_CATEGORY VARCHAR(50)
);

INSERT INTO DEPARTMENT_CLEAN(DEPARTMENTID, DEPARTMENTNAME, DEPARTMENT_CATEGORY)
